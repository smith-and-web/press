// Generate Markdown-parser metadata directly from the canonical Press source.
import {readFile,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
export async function buildDesignInput(){
  const css=(await readFile(resolve(root,'design-system/tokens.css'),'utf8')).replace(/\/\*[\s\S]*?\*\//g,'');
  const rootBlock=css.match(/:root\s*\{([\s\S]*?)\}/)?.[1];
  if(!rootBlock)throw new Error('Canonical :root token block is missing.');
  const declarations=new Map([...rootBlock.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(m=>[m[1],m[2].trim()]));
  function value(name,parents=[]){
    if(parents.includes(name))throw new Error(`Circular canonical token: ${name}`);
    if(!declarations.has(name))throw new Error(`Missing canonical token: ${name}`);
    return declarations.get(name).replace(/var\(\s*(--[\w-]+)\s*\)/g,(_,dependency)=>value(dependency,[...parents,name]));
  }
  function hex(name){const result=value(name);if(!/^#[\da-f]{6}$/i.test(result))throw new Error(`Expected solid canonical color: ${name}`);return result.toUpperCase();}
  const background=hex('--color-bg');
  // The simplified brand parser accepts solid hex colors, not translucent rules.
  // Describe the existing hairline composited onto paper; never change source CSS.
  const hair=value('--color-border').match(/^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)$/i);
  if(!hair)throw new Error('Expected canonical rgba hairline for compatibility metadata.');
  const alpha=Number(hair[4]);
  if(alpha<0||alpha>1)throw new Error('Invalid hairline alpha.');
  const border='#'+[0,1,2].map((channel)=>Math.round(Number(hair[channel+1])*alpha+parseInt(background.slice(1+channel*2,3+channel*2),16)*(1-alpha)).toString(16).padStart(2,'0')).join('').toUpperCase();
  const colorRoles={background,foreground:hex('--color-text'),accent:hex('--color-accent'),surface:hex('--color-surface'),muted:hex('--color-text-muted'),border};
  const family=name=>value(name).split(',')[0].replace(/^['"]|['"]$/g,'').trim();
  const fonts={display:family('--font-display'),body:family('--font-body'),ui:family('--font-ui'),mono:family('--font-mono')};
  const exports=await readFile(resolve(root,'design-system/svelte/index.ts'),'utf8');
  const editorExports=await readFile(resolve(root,'design-system/svelte/editor/index.ts'),'utf8');
  const components=[...exports.concat('\n',editorExports).matchAll(/export\s*\{\s*default as (\w+)\s*\}/g)].map(m=>m[1]);
  const quote=JSON.stringify;
  const metadata=['# Generated by scripts/build-design-input.mjs; edit canonical tokens, not these values.',
    'colors:',...Object.entries(colorRoles).map(([key,color])=>`  ${key}: ${quote(color)}`),
    'typography:',...Object.entries(fonts).map(([key,font])=>`  ${key}: ${quote(font)}`),
    `radius: ${quote(value('--radius-m'))}`,`spacing: ${quote(value('--space-3xs')+' base; use the full canonical scale')}`,
    'components:',...components.map(name=>`  ${name}: "Existing public Svelte component"`)
  ].join('\n');
  const designPath=resolve(root,'DESIGN.md');
  const design=await readFile(designPath,'utf8');
  const match=design.match(/^---\n([\s\S]*?)\n---\n/);
  if(!match)throw new Error('DESIGN.md frontmatter is missing; no replacement performed.');
  const marker='# Generated by scripts/build-design-input.mjs;';
  const authored=match[1].split(marker)[0].trimEnd();
  // Preserve every byte of authored body; only the generated metadata tail changes.
  await writeFile(designPath,`---\n${authored}\n${metadata}\n---\n${design.slice(match[0].length)}`);
  const compatibility=`---
name: "Press"
description: "Kindling’s paper-first design language for editorial websites and writing applications."
category: "Editorial"
surface: "web"
${metadata}
---

# Press

<!-- Generated by scripts/build-design-input.mjs from design-system/tokens.css and public exports. -->

## Overview

Press is Kindling’s paper-first, literary design system. Use ${fonts.display} for display, ${fonts.body} for manuscript prose, and ${fonts.ui} for operational controls. Preserve quiet editorial columns, measured reading widths, hairlines and restrained terracotta accents.

## Color palette

${Object.entries(colorRoles).map(([role,color])=>'- '+role+': '+color).join('\n')}

These are the light theme’s core roles. The border color is the existing translucent hairline composited over paper for a parser that only accepts solid hex. It is a compatibility representation, not a new canonical token. Use the small-text accent token from the canonical CSS for links; the accent above is the fill role.

## Typography

- Display family: ${fonts.display}
- Body family: ${fonts.body}
- UI family: ${fonts.ui}
- Mono family: ${fonts.mono}

The canonical font stacks, local files, variable weights and sizes remain in design-system/tokens.css and design-system/fonts.css. The simplified extractor retains display/body/mono roles and may omit the separate UI role or substitute fallback stacks and weights. Keep the native package for faithful rendering.

## Layout and interaction

Use the canonical spacing scale and ${value('--measure')} reading measure. The ${value('--radius-m')} radius is one common component size, not a universal replacement for the full radius scale. Preserve semantic controls, keyboard access, visible focus and state feedback. Dark application chrome retains a light paper manuscript through the prose tokens. Website copy uses an explicit scoped variant.

## Components

${components.map(name=>'- '+name).join('\n')}

NovelEditor is a page-style Tiptap WYSIWYG editor with rich HTML, formatting, alignment, blockquotes, indentation and undo/redo. Field’s multiline input must never replace prose editing. The consuming app owns saving, stores, APIs, shortcuts, cursor tracking and file workflows.

## How to supply this input

If using the extraction workflow, paste this entire document into its DESIGN.md input. Selecting the repository folder does not automatically select its DESIGN.md as the brief. Provide the actual local checkout path as source context for the agent; the browser folder snapshot is capped and cannot carry this complete repository.

For the full system, use native existing-package installation when available. See docs/OPEN_DESIGN.md for the distinction. This Markdown input prevents the empty-brief defaults from standing in for Press; it does not patch Open Design, install assets or skills, or repair an already-created Product record.

## Source authority

Read DESIGN.md for the complete design decisions, manifest.json for native package entries, and docs/APPLICATION_COMPONENTS.md for component APIs. This generated summary intentionally avoids mixing dark palette hex values into a single-palette extractor. The canonical CSS retains both themes unchanged.
`;
  await writeFile(resolve(root,'OPEN_DESIGN_INPUT.md'),compatibility);
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  await buildDesignInput();
  console.log('Generated Press DESIGN.md metadata and OPEN_DESIGN_INPUT.md from canonical source.');
}

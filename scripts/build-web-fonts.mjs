/* Publish the canonical font files for web delivery.
 *
 * Press owns the font files. `design-system/fonts.css` serves the original
 * variable TTFs, which is right for a desktop application bundling its own
 * assets and wrong for a website paying for every byte over the wire. Before
 * this step each web consumer vendored its own WOFF2 from a third-party
 * package (Fontsource), which put a second set of @font-face declarations
 * under the same family names, with narrower axes and no Inter italic.
 *
 * This is the one conversion route. It is lossless and deterministic: WOFF2 is
 * a container format, so every axis, weight, italic and glyph in the canonical
 * TTF survives it. No subsetting — a consumer that wants a subset must state
 * the coverage it is dropping, and that decision does not belong here.
 *
 *   npm run fonts:build    write assets/fonts/web/ and design-system/fonts-web.css
 *   npm run fonts:check    verify both against the current canonical TTFs
 *
 * The manifest records the source TTF digest beside the published digest, so a
 * stale or hand-edited web font is detectable without re-running the encoder.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { compress } from 'wawoff2';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const digest = (buffer) => createHash('sha256').update(buffer).digest('hex');

/* family/style/weight mirror design-system/fonts.css exactly. The two files
   declare the same faces; only the container format and path differ. */
const FACES = [
  { family: 'Fraunces', style: 'normal', weight: '100 900', ttf: 'Fraunces[SOFT,WONK,opsz,wght].ttf', web: 'Fraunces-Variable.woff2' },
  { family: 'Newsreader', style: 'normal', weight: '200 800', ttf: 'Newsreader[opsz,wght].ttf', web: 'Newsreader-Variable.woff2' },
  { family: 'Newsreader', style: 'italic', weight: '200 800', ttf: 'Newsreader-Italic[opsz,wght].ttf', web: 'Newsreader-Variable-Italic.woff2' },
  { family: 'Inter', style: 'normal', weight: '100 900', ttf: 'Inter[opsz,wght].ttf', web: 'Inter-Variable.woff2' },
  { family: 'Inter', style: 'italic', weight: '100 900', ttf: 'Inter-Italic[opsz,wght].ttf', web: 'Inter-Variable-Italic.woff2' },
];

const header = '/* Generated by scripts/build-web-fonts.mjs from the canonical TTFs in\n' +
  '   assets/fonts/. Same families, axes, weights and glyph coverage as fonts.css,\n' +
  '   in WOFF2 for web delivery. Preserve the adjacent licenses in distributions.\n' +
  '   Do not hand-edit; run `npm run fonts:build`. */\n';

const stylesheet = header + FACES.map((face) => `@font-face {
  font-family: '${face.family}'; font-style: ${face.style}; font-weight: ${face.weight}; font-display: swap;
  src: url('../assets/fonts/web/${face.web}') format('woff2');
}`).join('\n') + '\n';

await mkdir(resolve(root, 'assets/fonts/web'), { recursive: true });
const records = [];
let stale = [];

for (const face of FACES) {
  const ttf = await readFile(resolve(root, 'assets/fonts', face.ttf));
  const woff2 = Buffer.from(await compress(ttf));
  const record = {
    family: face.family,
    style: face.style,
    weight: face.weight,
    source: `assets/fonts/${face.ttf}`,
    sourceSha256: digest(ttf),
    sourceBytes: ttf.length,
    published: `assets/fonts/web/${face.web}`,
    sha256: digest(woff2),
    bytes: woff2.length,
  };
  records.push(record);
  const target = resolve(root, 'assets/fonts/web', face.web);
  if (check) {
    const current = await readFile(target).catch(() => null);
    if (!current || digest(current) !== record.sha256) stale.push(record.published);
  } else {
    await writeFile(target, woff2);
    console.log(`${record.published}  ${(ttf.length / 1024).toFixed(0)}K TTF -> ${(woff2.length / 1024).toFixed(0)}K WOFF2`);
  }
}

const manifest = JSON.stringify({
  generator: 'scripts/build-web-fonts.mjs',
  encoder: `wawoff2@${JSON.parse(await readFile(resolve(root, 'node_modules/wawoff2/package.json'), 'utf8').catch(() => '{"version":"unknown"}')).version}`,
  note: 'Lossless container conversion of the canonical TTFs. No subsetting; axes, weights, italics and glyph coverage are unchanged.',
  stylesheet: 'design-system/fonts-web.css',
  faces: records,
}, null, 2) + '\n';

for (const [path, contents] of [['assets/fonts/web/MANIFEST.json', manifest], ['design-system/fonts-web.css', stylesheet]]) {
  const target = resolve(root, path);
  if (check) {
    const current = await readFile(target, 'utf8').catch(() => null);
    /* The encoder version line is environment-reported; compare the faces only. */
    const strip = (text) => text.replace(/^\s*"encoder":.*$/m, '');
    if (current === null || strip(current) !== strip(contents)) stale.push(path);
  } else {
    await writeFile(target, contents);
    console.log(`wrote ${path}`);
  }
}

if (check) {
  if (stale.length) {
    console.error(`Stale web fonts; run \`npm run fonts:build\`:\n  ${stale.join('\n  ')}`);
    process.exit(1);
  }
  console.log(`Web fonts match the canonical TTFs (${FACES.length} faces).`);
}
